"""Publishes a LoRA adapter to Hugging Face with a model card (base model, data, training setup, val accuracy).

HF_TOKEN=... python -m hw4.hub --run sft_mamay_pot --eval-run sft_mamay_pot_eval --repo <user>/mamaylm-4b-ukr-math-pot
Uses the run's config.json / metrics.json and, for data, the teacher runs' metrics.json.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from . import MODELS
from .runs import RUNS

CARD = """---
base_model: {base}
library_name: peft
license: gemma
language: [uk]
tags: [lora, math, ukrainian, gemma3, tool-use]
---

# {repo}

LoRA adapter for **{base}** that solves Ukrainian grade-5 math word problems by writing a short Python program
(the result is stored in `answer` and executed by the caller). Made for Homework 4 of the UCU AI 2026 course
(Kaggle: *Ukrainian School Math with Small LLMs*).

## Training data
{data}

Synthetic problems were generated by my own Python generators (random numbers in templates for each of the 29
skills, exact answers computed by the generator). Teacher solutions were written by the open model
**{teacher}** (non-thinking mode) and kept **only if executing them gave the reference answer**. No validation or
test problems were used; no proprietary models were used.

## Training setup
- method: {method}; LoRA r={rank}, alpha={alpha}, dropout 0.05, on q/k/v/o/gate/up/down projections of the language model
- {hparams}
- bf16, gradient checkpointing, TRL + PEFT

## Evaluation
Validation: a fixed 30% split of the competition `train.csv` (458 problems, stratified by skill, seed 42).

| model | prompt | val accuracy |
|---|---|---|
| {base} (no fine-tuning) | {base_strategy} | {base_acc} |
| this adapter | {strategy} | **{acc}** |

## Usage
Prompt (Ukrainian) and execution code: see the project repository{repo_link}. Answers are normalized to the
competition format (integer, decimal with a dot, or reduced fraction a/b).
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True, help="training run with adapter/")
    ap.add_argument("--eval-run", required=True, help="infer run of the merged model")
    ap.add_argument("--base-eval-run", default=None, help="best prompting run of the base model")
    ap.add_argument("--repo", required=True)
    ap.add_argument("--repo-link", default="")
    ap.add_argument("--private", action="store_true")
    ap.add_argument("--dry", action="store_true", help="only write the model card")
    a = ap.parse_args()

    d = Path(RUNS) / a.run
    cfg = json.loads((d / "config.json").read_text())
    ev = json.loads((Path(RUNS) / a.eval_run / "metrics.json").read_text())
    evc = json.loads((Path(RUNS) / a.eval_run / "config.json").read_text())
    base = MODELS.get(cfg["model"], (cfg["model"],))[0]
    data_lines, teacher = [], "Qwen/Qwen3-8B"
    for p in cfg.get("data", []):
        td = Path(p).parent
        if (td / "metrics.json").exists():
            tm, tc = json.loads((td / "metrics.json").read_text()), json.loads((td / "config.json").read_text())
            teacher = tc.get("teacher", teacher)
            data_lines.append(f"- `{td.name}`: {tm['kept']} verified solutions ({tc['style']}) for {tm['problems']} "
                              f"problems from `{tc['source']}` (teacher solved {tm['solved']:.1%})")
    method = "DPO" if "beta" in cfg and "samples" in cfg else ("GRPO" if "num_generations" in cfg else "SFT")
    hp = {k: cfg[k] for k in ("epochs", "lr", "bs", "grad_accum", "max_steps", "beta", "n_train", "n_pairs") if k in cfg}
    base_acc = base_strategy = "-"
    if a.base_eval_run:
        bm = json.loads((Path(RUNS) / a.base_eval_run / "metrics.json").read_text())
        bc = json.loads((Path(RUNS) / a.base_eval_run / "config.json").read_text())
        base_acc, base_strategy = f"{bm['val_acc']:.3f}", bc["strategy"]
    card = CARD.format(base=base, repo=a.repo, data="\n".join(data_lines) or "- see config", teacher=teacher,
                       method=method, rank=cfg["rank"], alpha=2 * cfg["rank"],
                       hparams=", ".join(f"{k}={v}" for k, v in hp.items()), base_strategy=base_strategy,
                       base_acc=base_acc, strategy=evc["strategy"], acc=f"{ev['val_acc']:.3f}",
                       repo_link=f": {a.repo_link}" if a.repo_link else "")
    (d / "adapter" / "README.md").write_text(card)
    if a.dry:
        print(card)
        return

    from huggingface_hub import HfApi
    api = HfApi()
    api.create_repo(a.repo, private=a.private, exist_ok=True)
    api.upload_folder(folder_path=str(d / "adapter"), repo_id=a.repo, commit_message=f"{a.run}: val acc {ev['val_acc']:.3f}")
    print("published https://huggingface.co/" + a.repo)


if __name__ == "__main__":
    main()
